"""Иерархия исключений приложения.

Все ошибки, которые приложение осознанно порождает, наследуются от
:class:`CertMatcherError`. Это позволяет GUI-слою отличать «ожидаемые»
доменные ошибки (показываем аккуратное уведомление) от программных дефектов
(логируем полный traceback и показываем диалог «непредвиденная ошибка»).
"""

from __future__ import annotations

from pathlib import Path


class CertMatcherError(Exception):
    """Базовое исключение приложения.

    Attributes:
        message: Человекочитаемое сообщение (показывается пользователю).
        details: Технические подробности (попадают в лог, но не в UI).
    """

    def __init__(self, message: str, *, details: str | None = None) -> None:
        """Создаёт исключение с пользовательским и техническим сообщением."""
        super().__init__(message)
        self.message = message
        self.details = details

    def __str__(self) -> str:
        """Возвращает пользовательское сообщение."""
        return self.message


# --------------------------------------------------------------------------- #
# Конфигурация
# --------------------------------------------------------------------------- #
class ConfigurationError(CertMatcherError):
    """Некорректная или недоступная конфигурация приложения."""


# --------------------------------------------------------------------------- #
# Хранилище
# --------------------------------------------------------------------------- #
class StorageError(CertMatcherError):
    """Базовая ошибка слоя хранения данных."""


class DatabaseError(StorageError):
    """Ошибка работы с SQLite."""


class MigrationError(DatabaseError):
    """Ошибка применения миграции схемы."""


class DuplicateAliasError(StorageError):
    """Точно такое же соответствие уже есть в словаре."""


# --------------------------------------------------------------------------- #
# Разбор файлов
# --------------------------------------------------------------------------- #
class ParsingError(CertMatcherError):
    """Базовая ошибка разбора внешнего файла."""

    def __init__(
        self, message: str, *, path: Path | None = None, details: str | None = None
    ) -> None:
        """Сохраняет путь к проблемному файлу вместе с сообщением."""
        super().__init__(message, details=details)
        self.path = path


class PdfParsingError(ParsingError):
    """PDF-файл не удалось прочитать или он повреждён."""


class ExcelParsingError(ParsingError):
    """Файл заказа не удалось прочитать или его структура не распознана."""


class ColumnMappingError(ExcelParsingError):
    """В файле заказа не найдена обязательная колонка с наименованием товара."""


# --------------------------------------------------------------------------- #
# Подбор
# --------------------------------------------------------------------------- #
class MatchingError(CertMatcherError):
    """Ошибка на этапе подбора сертификатов."""


class EmbeddingBackendError(MatchingError):
    """Семантический бэкенд недоступен или не смог загрузить модель."""


# --------------------------------------------------------------------------- #
# Операции с файлами результата
# --------------------------------------------------------------------------- #
class ExportError(CertMatcherError):
    """Ошибка формирования результата (Excel, отчёт, копирование PDF)."""


class OperationCancelledError(CertMatcherError):
    """Длительная операция была отменена пользователем."""

    def __init__(self, message: str = "Операция отменена пользователем") -> None:
        """Создаёт исключение отмены со стандартным сообщением."""
        super().__init__(message)
